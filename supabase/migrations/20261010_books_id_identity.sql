-- books.id 에 identity 가 없을 때만 추가하는 안전장치입니다.
-- 운영 DB 에는 이미 identity 가 있어 실제로는 아무 것도 바꾸지 않았습니다(적용 기록 유지용).
-- 시퀀스가 기존 id 와 어긋난 문제는 20261011_books_id_sequence_sync.sql 에서 해결합니다.
do $$
declare
  next_id bigint;
begin
  if exists (
    select 1
    from information_schema.columns
    where table_schema = 'public'
      and table_name = 'books'
      and column_name = 'id'
      and is_identity = 'NO'
      and column_default is null
  ) then
    alter table public.books alter column id add generated by default as identity;
    select coalesce(max(id), 0) + 1 into next_id from public.books;
    execute format('alter table public.books alter column id restart with %s', next_id);
  end if;
end $$;
