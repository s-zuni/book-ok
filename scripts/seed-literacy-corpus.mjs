async function runSeed() {
    console.log(`Starting literacy corpus seeding (${SEED_CORPUS.length} passages across grades 0~6)...`);

    for (const item of SEED_CORPUS) {
        const embeddingInput = `[학년: ${item.grade_level}] [장르: ${item.genre}] [관심사: ${item.interest_tags.join(', ')}] ${item.title}\n${item.content}`;

        // Check if passage with same title already exists
        const { data: existing } = await supabase
            .from('literacy_passages')
            .select('id, embedding')
            .eq('title', item.title)
            .maybeSingle();

        if (existing) {
            if (!existing.embedding) {
                const emb = await createEmbedding(embeddingInput);
                if (emb) {
                    await supabase
                        .from('literacy_passages')
                        .update({ embedding: emb })
                        .eq('id', existing.id);
                    console.log(`🔄 Backfilled 1536d embedding for: [Grade ${item.grade_level}] ${item.title}`);
                } else {
                    console.log(`[Skip] Already exists (no embedding): [Grade ${item.grade_level}] ${item.title}`);
                }
            } else {
                console.log(`[Skip] Already exists with embedding: [Grade ${item.grade_level}] ${item.title}`);
            }
            continue;
        }

        const wordCount = item.content.trim().split(/\s+/).length;
        const charCount = item.content.trim().length;
        const embedding = await createEmbedding(embeddingInput);

        const { data: insertedPassage, error: passageErr } = await supabase
            .from('literacy_passages')
            .insert({
                title: item.title,
                content: item.content,
                grade_level: item.grade_level,
                genre: item.genre,
                interest_tags: item.interest_tags,
                word_count: wordCount,
                char_count: charCount,
                source_attribution: item.source_attribution,
                key_vocabularies: item.key_vocabularies,
                embedding,
                is_active: true,
            })
            .select('id')
            .single();

        if (passageErr || !insertedPassage) {
            console.error(`Failed to insert passage "${item.title}":`, passageErr);
            continue;
        }

        const questionsPayload = item.questions.map((q) => ({
            passage_id: insertedPassage.id,
            area: q.area,
            question: q.question,
            options: q.options,
            correct_answer: q.correct_answer,
            evidence: q.evidence,
            explanation: q.explanation,
            critic_score: 100,
            is_verified: true,
        }));

        const { error: qErr } = await supabase
            .from('literacy_questions')
            .insert(questionsPayload);

        if (qErr) {
            console.error(`Failed to insert questions for "${item.title}":`, qErr);
        } else {
            console.log(`✅ Seeded [Grade ${item.grade_level} | ${item.genre}] "${item.title}" (${wordCount} words, ${questionsPayload.length} questions, embedding: ${embedding ? '1536d' : 'none'})`);
        }
    }

    console.log('🎉 Literacy corpus seeding complete!');
}

runSeed().catch((err) => {
    console.error('Seed fatal error:', err);
    process.exit(1);
});
